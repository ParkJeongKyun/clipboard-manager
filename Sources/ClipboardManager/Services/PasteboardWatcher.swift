import AppKit

/// NSPasteboard에는 변경 알림이 없어서 changeCount를 짧은 주기로 확인한다.
/// changeCount 비교는 매우 가벼워서 0.25초 주기여도 CPU 부담이 거의 없다.
@MainActor
final class PasteboardWatcher {
    private let store: ClipboardStore
    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount = 0
    /// 직전 확인 때 맨 앞에 있던 앱
    private var previousFrontmostBundleID: String?

    /// 비밀번호 관리자 등이 "기록하지 말라"고 표시할 때 쓰는 타입 (nspasteboard.org)
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType")
    ]

    init(store: ClipboardStore) {
        self.store = store
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        // 허용 오차를 두면 macOS가 다른 작업과 묶어서 깨워 전력을 아낀다
        timer.tolerance = 0.1
        // 메뉴가 열려 있는 동안(.eventTracking)에도 동작하도록 common 모드에 등록
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        // 시작 시점에 이미 클립보드에 있던 내용은 기록하지 않는다.
        // 어느 앱에서 복사했는지 알 수 없어서 "기록하지 않을 앱" 규칙을 지킬 수 없기 때문 (재시작/업데이트 직후 포함)
        lastChangeCount = pasteboard.changeCount
        previousFrontmostBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
    }

    /// 복사가 일어났을 수 있는 앱 (첫 번째를 출처로 기록).
    /// 확인 사이(최대 0.25초)에 다른 앱으로 넘어갔다면 어느 앱에서 복사했는지 확실하지 않다.
    /// 보통은 복사하고 나서 앱을 바꾸므로 이전 앱을 출처로 보고, 제외 규칙은 두 앱 모두에 적용한다
    /// (비밀번호 앱에서 복사하자마자 다른 앱으로 넘어가도 기록되지 않도록).
    static func possibleSources(previous: String?, current: String?) -> [String?] {
        previous == current ? [current] : [previous, current]
    }

    private func poll() {
        let frontmost = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let previous = previousFrontmostBundleID
        previousFrontmostBundleID = frontmost

        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        guard store.isMonitoring, let types = pasteboard.types else { return }
        if types.contains(where: Self.ignoredTypes.contains) { return }
        let sources = Self.possibleSources(previous: previous, current: frontmost)
        guard sources.allSatisfy(store.shouldRecord(from:)) else { return }
        let sourceBundleID = sources[0]

        // 엑셀 셀처럼 텍스트와 이미지가 함께 복사되면 텍스트를 기록한다
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            store.record(text, sourceBundleID: sourceBundleID)
        } else if store.recordsImages {
            recordImage(types: types, sourceBundleID: sourceBundleID)
        }
    }

    /// PNG 변환과 해시 계산은 큰 이미지에서 수백 ms가 걸릴 수 있어 백그라운드에서 한다
    private func recordImage(types: [NSPasteboard.PasteboardType], sourceBundleID: String?) {
        guard let type = [NSPasteboard.PasteboardType.png, .tiff].first(where: types.contains),
              let data = pasteboard.data(forType: type),
              data.count <= Self.maxImageInputBytes(for: type) else { return }

        let date = Date()
        let store = store
        Task.detached(priority: .utility) {
            guard let image = ClipboardImage(pasteboardData: data, type: type),
                  image.pngData.count <= PrivacyRules.maxImageBytes else { return }
            _ = ImageThumbnails.thumbnail(for: image)  // 목록에 처음 보일 때 멈추지 않도록 미리 만든다
            await store.record(image, sourceBundleID: sourceBundleID, at: date)
        }
    }

    /// 변환 전에 걸러낼 원본 크기. TIFF는 압축이 없어 PNG로 바꾸면 보통 몇 분의 1로 줄어든다
    private static func maxImageInputBytes(for type: NSPasteboard.PasteboardType) -> Int {
        type == .png ? PrivacyRules.maxImageBytes : PrivacyRules.maxImageBytes * 25
    }
}
