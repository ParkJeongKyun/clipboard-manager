import AppKit

/// NSPasteboard에는 변경 알림이 없어서 changeCount를 짧은 주기로 확인한다.
/// changeCount 비교는 매우 가벼워서 0.25초 주기여도 CPU 부담이 거의 없다.
@MainActor
final class PasteboardWatcher {
    private let store: ClipboardStore
    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    /// -1로 시작해 앱이 꺼져 있는 동안 복사한 내용도 첫 확인 때 기록
    private var lastChangeCount = -1

    /// 비밀번호 관리자 등이 "기록하지 말라"고 표시할 때 쓰는 타입 (nspasteboard.org)
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType")
    ]

    init(store: ClipboardStore) {
        self.store = store
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.05
        // 메뉴가 열려 있는 동안(.eventTracking)에도 동작하도록 common 모드에 등록
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        poll()
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        guard store.isMonitoring else { return }
        if let types = pasteboard.types, types.contains(where: Self.ignoredTypes.contains) { return }
        guard let text = pasteboard.string(forType: .string), !text.isEmpty else { return }

        store.record(text, sourceBundleID: NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
    }
}
